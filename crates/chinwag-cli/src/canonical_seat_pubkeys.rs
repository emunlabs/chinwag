/// Look up the sole pinned 32-byte Ed25519 public key for `base_seat`.
pub fn canonical_seat_pubkey(base_seat: &str) -> Option<[u8; 32]> {
    let normalized = base_seat.trim().to_ascii_uppercase();
    CANONICAL_SEAT_PUBKEYS
        .binary_search_by(|(candidate, _)| (*candidate).cmp(normalized.as_str()))
        .ok()
        .map(|idx| CANONICAL_SEAT_PUBKEYS[idx].1)
}

/// Constant-time verification that `pubkey_bytes` equals `base_seat`'s sole
/// pinned Ed25519 public key.
pub fn verify_canonical_seat_pubkey(base_seat: &str, pubkey_bytes: &[u8; 32]) -> bool {
    let Some(expected) = canonical_seat_pubkey(base_seat) else {
        return false;
    };
    bool::from(expected.ct_eq(pubkey_bytes))
}
